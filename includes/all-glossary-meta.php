/**
 * Подбирает термины словаря, встречающиеся в тексте (для блока «Термины по теме»
 * в статьях — обратная перелинковка статья → словарь). Матч по названию и синонимам:
 * короткие ключи (УЗО, УЗМ, SPC) — по границам слова, длинные — по вхождению.
 */
if (!function_exists('domexpert_terms_for_text')) {
  function domexpert_terms_for_text(string $text, string $excludeSlug = '', int $limit = 8): array {
    $plain = ' ' . mb_strtolower(preg_replace('/\s+/u', ' ', strip_tags($text)), 'UTF-8') . ' ';
    $out = [];
    foreach (domexpert_all_glossary_meta() as $slug => $t) {
      if ($slug === $excludeSlug) { continue; }
      $keys = array_merge([$t['term']], $t['aliases'] ?? []);
      foreach ($keys as $k) {
        $k = mb_strtolower(trim($k), 'UTF-8');
        if ($k === '') { continue; }
        $hit = (mb_strlen($k) <= 4)
          ? (bool) preg_match('/(?<!\p{L})' . preg_quote($k, '/') . '(?!\p{L})/u', $plain)
          : (mb_strpos($plain, $k) !== false);
        if ($hit) { $out[$slug] = $t; break; }
      }
      if (count($out) >= $limit) { break; }
    }
    return $out;
  }
}

