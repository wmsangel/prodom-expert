def _shade(hex_color: str, delta: int) -> str:
    h = hex_color.lstrip("#")
    rgb = [max(0, min(255, int(h[i : i + 2], 16) + delta)) for i in (0, 2, 4)]
    return "#{:02x}{:02x}{:02x}".format(*rgb)


def make_table_image(slug: str, headers: list[str], rows: list[list[str]], accent: str) -> str:
    """Simple comparison table as PNG for in-article use."""
    col_w = 220
    row_h = 44
    pad = 24
    w = pad * 2 + col_w * len(headers)
    h = pad * 2 + row_h * (1 + len(rows))
    img = Image.new("RGB", (w, h), "#FAFAF8")
    d = ImageDraw.Draw(img)
    d.rectangle([0, 0, w, row_h + pad], fill=accent)
    for i, head in enumerate(headers):
        d.text((pad + i * col_w + 8, pad + 10), head[:28], font=font(16, True), fill="#FFFFFF")
    for r, row in enumerate(rows):
        y = pad + row_h * (r + 1)
        if r % 2 == 0:
            d.rectangle([0, y, w, y + row_h], fill="#F0EEE8")
        for c, cell in enumerate(row):
            d.text((pad + c * col_w + 8, y + 12), cell[:30], font=font(15), fill="#222222")
    path = INLINE / f"{slug}-table.png"
    img.save(path, "PNG", optimize=True)
    return f"/assets/img/inline/{slug}-table.png"


def fig(src: str, alt: str) -> str:
    return (
        f'<figure style="margin:1.5rem 0;">'
        f'<img src="{src}" alt="{alt}" width="960" height="auto" '
        f'loading="lazy" decoding="async" '
        f'style="width:100%;height:auto;border-radius:8px;display:block;">'
        f'<figcaption style="margin-top:0.5rem;color:#666;font-size:0.9rem;">{alt}</figcaption>'
        f"</figure>"
    )


def tbl(headers: list[str], rows: list[list[str]]) -> str:
    th = "".join(
        f'<th style="padding:10px;border:1px solid #ddd;text-align:left;background:#f5f5f5;">{h}</th>'
        for h in headers
    )
    body = []
    for row in rows:
        tds = "".join(f'<td style="padding:10px;border:1px solid #ddd;">{c}</td>' for c in row)
        body.append(f"<tr>{tds}</tr>")
    return (
        '<div style="overflow-x:auto;margin:1.25rem 0;">'
        '<table style="width:100%;border-collapse:collapse;min-width:560px;">'
        f"<thead><tr>{th}</tr></thead><tbody>{''.join(body)}</tbody></table></div>"
    )


